  const ICON_DOWN = '<svg viewBox="0 0 24 24" aria-hidden="true"><path d="M17 13V4h3v9h-3zm0 0l-4 8c-1.700 0-3-1.300-3-3v-3H5c-1.100 0-2-.900-1.900-2l1.200-7c.200-1 1-1.700 2-1.700H17"/></svg>';
  const DOTS = '<span class="mcp-ask-dots" aria-hidden="true"><i></i><i></i><i></i></span>';

  const el = (tag, className, text) => {
    const node = document.createElement(tag);

    node.className = className;

    if (text !== undefined) {
      node.textContent = text;
    }

    return node;
  };

  // ---------- Answer text: a small, escaped subset of Markdown ----------

  // Also removes the character used below to set links aside
  const escape = (text) => String(text).replace(/\u0000/g, '').replace(/[&<>"']/g, (char) => `&#${char.charCodeAt(0)};`);

  const safeUrl = (url) => {
    try {
      const parsed = new URL(url, document.baseURI);

      return ['http:', 'https:'].includes(parsed.protocol) ? parsed.href : '';
    } catch (error) {
      return '';
    }
  };

  const cleanSources = (items) => (Array.isArray(items) ? items : [])
    .map((item) => ({
      title: String((item && item.title) || '').slice(0, 200),
      section: String((item && item.section) || '').slice(0, 200),
      site: String((item && item.site) || '').slice(0, 100),
      url: safeUrl(item && item.url),
    }))
    .filter((item) => item.url)
    // As many as the server numbers: a citation must never point past the end of the list
    .slice(0, 50);

  // How many pages beside an answer before the rest are folded into one line; 0 for all of them
  const sourcesShown = (() => {
    const value = Number(roots.map((root) => root.dataset.sourcesShown).find((item) => item !== undefined));

    return Number.isFinite(value) && value >= 0 ? Math.round(value) : 3;
  })();

  // Sites links in answers may lead to (the server has already removed any others)
  const allowedHosts = (() => {
    try {
      const hosts = JSON.parse(roots[0].dataset.allowedHosts || '[]');

      return Array.isArray(hosts) ? hosts.map((host) => String(host).toLowerCase()) : [];
    } catch (error) {
      return [];
    }
  })();

  const linkable = (href) => {
    const url = new URL(href);
    const host = url.hostname.toLowerCase();

    if (url.origin === window.location.origin) {
      return true;
    }

    return url.protocol === 'https:' && allowedHosts.some((allowed) => allowed === host
      || (allowed.startsWith('*.') && (host.endsWith(allowed.slice(1)) || host === allowed.slice(2))));
  };

  // Images in answers are files of this site, given as paths from its root: the server lets
  // through only those of the pages the answer was written from, and nothing else is shown here
  const siteRoot = (roots[0].dataset.siteRoot || '').replace(/\/+$/, '');
  const IMAGE_PATH = /^\/(?!\/)[^\s"'<>()?#\\]+\.(?:jpe?g|png|gif|webp|avif)$/i;

  const image = (alt, path) => {
    const decoded = path.replace(/&#38;/g, '&');

    if (!IMAGE_PATH.test(decoded) || /(^|\/)\.\.(\/|$)/.test(decoded)) {
      return '';
    }

    return `<img class="mcp-ask-image" src="${escape(siteRoot + decoded)}" alt="${alt}" loading="lazy" decoding="async">`;
  };

  const inline = (text, sources) => {
    const links = [];

    return escape(text)
      // Images first, set aside like links, so nothing below is applied inside them
      .replace(/!\[([^\]]{0,200})\]\(([^()\s]{1,500})\)/g, (match, alt, path) => {
        links.push(image(alt, path));

        return `\u0000${links.length - 1}\u0000`;
      })
      .replace(/`([^`]+)`/g, '<code>$1</code>')
      .replace(/\*\*([^*]+)\*\*/g, '<strong>$1</strong>')
      // The answer is asked not to contain links. If one appears all the same, it is only made
      // clickable when it stays on this site: an indexed page must not be able to send visitors
      // elsewhere through the answer. Links are set aside so nothing below is applied inside them.
      // The address may hold one level of brackets, as javascript:alert(1) does
      .replace(/\[([^\]]+)\]\(((?:[^()\s]|\([^()\s]*\))+)\)/g, (match, label, url) => {
        const href = safeUrl(url.replace(/&#38;/g, '&'));

        if (!href || !linkable(href)) {
          return label;
        }

        const away = new URL(href).origin !== window.location.origin;

        links.push(`<a href="${escape(href)}" rel="noopener noreferrer nofollow"${away ? ' target="_blank"' : ''}>${label}</a>`);

        return `\u0000${links.length - 1}\u0000`;
      })
      // A group of citations wrapped in brackets once more, [[1][2]], loses the extra pair
      .replace(/[\[［【]((?:\s*[\[［【]\d{1,3}[\]］】])+)\s*[\]］】]/g, '$1')
      // Citations, also in full-width brackets; a number with no page behind it is dropped
      .replace(/\s?[\[［【](\d{1,3})[\]］】]/g, (match, number) => {
        const source = sources[number - 1];

        return source
          ? `${match.startsWith(' ') ? ' ' : ''}<a class="mcp-ask-cite" href="${escape(source.url)}" title="${escape(source.title)}">${number}</a>`
          : '';
      })
      .replace(/\u0000(\d+)\u0000/g, (match, index) => links[index] || '');
  };

  const CALLOUTS = {
    NOTE: 'note', TIP: 'tip', IMPORTANT: 'note', WARNING: 'warning', CAUTION: 'warning',
    提示: 'tip', 小提醒: 'tip', 說明: 'note', 備註: 'note', 重要: 'note', 注意: 'warning', 警告: 'warning',
  };

  const markdown = (text, sources) => {
    const out = [];
    let paragraph = [];
    let list = null;
    let code = null;
    let table = null;
    let quote = null;

    const endParagraph = () => {
      if (paragraph.length) {
        out.push(`<p>${paragraph.join('<br>')}</p>`);
        paragraph = [];
      }
    };
    const endList = () => {
      if (list) {
        const start = list.tag === 'ol' && list.start > 1 ? ` start="${list.start}"` : '';

        out.push(`<${list.tag}${start}>${list.items.map((item) => `<li>${item}</li>`).join('')}</${list.tag}>`);
        list = null;
      }
    };
    const endCode = () => {
      out.push(`<pre><code>${escape(code.join('\n'))}</code></pre>`);
      code = null;
    };
    const cells = (line) => line.trim().replace(/^\|/, '').replace(/\|$/, '').split('|').map((cell) => inline(cell.trim(), sources));
    const endTable = () => {
      if (table) {
        // A separator row (|---|---|) marks the first row as the header; without one the first row is taken as the header
        const rows = table.filter((row) => !/^\s*\|?\s*:?-{2,}:?\s*(\|\s*:?-{2,}:?\s*)*\|?\s*$/.test(row));
        const [head, ...body] = rows.map(cells);

        if (head) {
          out.push(`<div class="mcp-ask-table"><table><thead><tr>${head.map((cell) => `<th>${cell}</th>`).join('')}</tr></thead>`
            + `<tbody>${body.map((row) => `<tr>${row.map((cell) => `<td>${cell}</td>`).join('')}</tr>`).join('')}</tbody></table></div>`);
        }

        table = null;
      }
    };
    const endQuote = () => {
      if (quote) {
        const kind = quote.kind ? ` mcp-ask-callout mcp-ask-callout--${quote.kind}` : '';
        const label = quote.kind ? `<div class="mcp-ask-callout__label">${escape(strings[`callout${quote.kind[0].toUpperCase()}${quote.kind.slice(1)}`] || quote.label)}</div>` : '';

        out.push(`<blockquote class="mcp-ask-quote${kind}">${label}${markdown(quote.lines.join('\n'), sources)}</blockquote>`);
        quote = null;
      }
    };
    const endBlocks = () => {
      endParagraph();
      endList();
      endTable();
      endQuote();
    };

    text.split('\n').forEach((line) => {
      if (code) {
        if (line.startsWith('```')) {
          endCode();
        } else {
          code.push(line);
        }

        return;
      }

      // A callout or a quotation: "> [!TIP]" then lines starting with ">"
      const quoted = line.match(/^\s*>\s?(.*)$/);

      if (quoted) {
        if (!quote) {
          endBlocks();

          const callout = quoted[1].match(/^\[!([A-Za-z]{3,9}|\p{Script=Han}{2,3})\]\s*(.*)$/u);
          const kind = callout ? CALLOUTS[callout[1].toUpperCase()] || '' : '';

          quote = { kind, label: kind ? callout[1] : '', lines: [] };

          if (kind) {
            if (callout[2]) {
              quote.lines.push(callout[2]);
            }

            return;
          }
        }

        quote.lines.push(quoted[1]);

        return;
      }

      endQuote();

      if (/^\s*\|.*\|\s*$/.test(line)) {
        endParagraph();
        endList();
        table = table || [];
        table.push(line);

        return;
      }

      endTable();

      const heading = line.match(/^(#{1,6})\s+(.*)$/);
      const item = line.match(/^\s*(?:([-*•])|(\d+)[.)])\s+(.*)$/);
      const lone = line.match(/^\s*(!\[[^\]]{0,200}\]\([^()\s]{1,500}\))\s*$/);

      if (line.startsWith('```')) {
        endBlocks();
        code = [];
      } else if (heading) {
        endBlocks();

        const tag = heading[1].length < 3 ? 'h3' : 'h4';

        out.push(`<${tag}>${inline(heading[2], sources)}</${tag}>`);
      } else if (item) {
        const tag = item[1] ? 'ul' : 'ol';

        endParagraph();

        if (!list || list.tag !== tag) {
          endList();
          list = { tag, items: [], start: item[2] ? Number(item[2]) : 1 };
        }

        list.items.push(inline(item[3], sources));
      } else if (lone && list) {
        // The screenshot of a step belongs to that step, and the numbering goes on after it
        list.items[list.items.length - 1] += `<span class="mcp-ask-figure">${inline(lone[1], sources)}</span>`;
      } else if (list && /^\s{2,}\S/.test(line)) {
        // An indented line goes on with the item above it (a screenshot with its citation, say)
        const figure = line.match(/^\s*(!\[[^\]]{0,200}\]\([^()\s]{1,500}\))(.*)$/);

        list.items[list.items.length - 1] += figure
          ? `<span class="mcp-ask-figure">${inline(figure[1], sources)}</span>${inline(figure[2].trim(), sources)}`
          : `<br>${inline(line.trim(), sources)}`;
      } else if (lone) {
        endParagraph();
        out.push(`<p class="mcp-ask-figure">${inline(lone[1], sources)}</p>`);
      } else if (!line.trim()) {
        // A blank line ends a paragraph, but list items may be separated by one
        endParagraph();
      } else {
        endList();
        paragraph.push(inline(line, sources));
      }
    });

    if (code) {
      endCode();
    }

    endBlocks();

    return out.join('');
  };

  // ---------- Transport: POST the question, read server-sent events ----------
  // Events: status {text} · sources {items: [{title, url, section}]} · delta {text} · error {message} · done

  class AskError extends Error {}

  async function* readEvents(stream) {
    const reader = stream.pipeThrough(new TextDecoderStream()).getReader();
    let buffer = '';

    try {
      for (;;) {
        const { value, done } = await reader.read();

        if (done) {
          return;
        }

        const frames = (buffer + value).split(/\r?\n\r?\n/);

        buffer = frames.pop();

        for (const frame of frames) {
          let event = 'message';
          const data = [];

          frame.split(/\r?\n/).forEach((line) => {
            if (line.startsWith('event:')) {
              event = line.slice(6).trim();
            } else if (line.startsWith('data:')) {
              data.push(line.slice(5).trimStart());
            }
          });

          if (data.length) {
            yield { event, data: parse(data.join('\n')) };
          }
        }
      }
    } finally {
      reader.cancel().catch(() => {});
    }
  }

  // ---------- Embedded on another website ----------

  // In a frame on another website (the component's embed page): which key, which website, the
  // sign-in window. That website's page is told what to do (grow, shrink, change page, open
  // LiveChat) and tells where its visitor is; both sides check who they are talking to.
  const embed = (() => {
    try {
      const value = JSON.parse(roots.map((root) => root.dataset.embed).find(Boolean) || 'null');

      return value && /^pk_[0-9a-f]{24}$/.test(value.key) && /^https?:\/\/[^/]+$/.test(value.host) && window.parent !== window ? value : null;
    } catch (error) {
      return null;
    }
  })();

  const hostHeard = {};
  const hostPost = (type, data = {}) => {
    if (embed) {
      window.parent.postMessage({ ...data, mcpAsk: type }, embed.host);
    }
  };
  const onHost = (type, callback) => {
    (hostHeard[type] = hostHeard[type] || []).push(callback);

    return () => {
      hostHeard[type] = hostHeard[type].filter((item) => item !== callback);
    };
  };

  if (embed) {
    window.addEventListener('message', (event) => {
      if (event.source !== window.parent || event.origin !== embed.host || !event.data || typeof event.data.mcpAsk !== 'string') {
        return;
      }

      [...(hostHeard[event.data.mcpAsk] || [])].forEach((callback) => callback(event.data));
    });
  }

  // Where the visitor is on that website: its address and title, and what its page says about it
  let hostPage = { url: '', title: '', context: '' };
  const plain = (value, length) => String(value == null ? '' : value).replace(/[\u0000-\u001f\u007f]+/g, ' ').trim().slice(0, length);

  onHost('context', (data) => {
    const extra = data.context && typeof data.context === 'object' ? data.context : {};

    hostPage = {
      url: /^https?:\/\//i.test(String(data.url || '')) ? String(data.url).slice(0, 490) : '',
      title: plain(data.title, 150),
      context: Object.entries(extra).slice(0, 10).map(([name, value]) => `${plain(name, 40)}: ${plain(value, 100)}`).join('; ').slice(0, 140),
    };
  });

  // Who the visitor is: a token from the sign-in window, or one the other website's server signed
  const IDENTITY = 'mcp-ask:identity';
  let identity = (() => {
    try {
      const kept = JSON.parse(sessionStorage.getItem(IDENTITY));

      return embed && kept && typeof kept.token === 'string' && kept.key === embed.key && Number(kept.until) > Date.now() ? kept : null;
    } catch (error) {
      return null;
    }
  })();
  const identityHeard = [];

  const keepIdentity = (value) => {
    identity = value;

    try {
      if (value) {
        sessionStorage.setItem(IDENTITY, JSON.stringify(value));
      } else {
        sessionStorage.removeItem(IDENTITY);
      }
    } catch (error) {
      // Signed in until the page is left
    }

    identityHeard.forEach((callback) => callback());
  };

  onHost('user', (data) => {
    if (typeof data.token === 'string' && data.token.length < 4000) {
      keepIdentity({ key: embed.key, token: data.token, name: plain(data.name, 100), until: Date.now() + 3600 * 1000, product: true });
    } else if (data.token === null && identity && identity.product) {
      keepIdentity(null);
    }
  });

  // Sent with every request when embedded
  const embedHeaders = () => (embed ? { 'X-Mcp-Ask-Embed': embed.key, ...(identity ? { 'X-Mcp-Ask-Identity': identity.token } : {}) } : {});

  const fetchTransport = (endpoint) => async function* transport(request, signal) {
    const response = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', Accept: 'text/event-stream', ...embedHeaders() },
      body: JSON.stringify(request),
      credentials: 'same-origin',
      signal,
    });

    if (!response.ok || !response.body) {
      throw new AskError(strings.error);
    }

    yield* readEvents(response.body);
  };

  // ---------- Conversation, kept for this browser tab ----------

  const messages = [];

  const save = () => {
    const kept = messages
      .filter((message) => (message.text || (message.role === 'agent' && message.cards && message.cards.length)) && !message.pending)
      .map(({ role, text, sources, ref, rating, explained, offer, cards, agent: who }) => (role === 'agent'
        ? { role, cards, agent: who }
        : { role, text, sources, ref, rating, explained, offer }));

    try {
      if (kept.length) {
        sessionStorage.setItem(STORE, JSON.stringify(kept));
      } else {
        sessionStorage.removeItem(STORE);
      }
    } catch (error) {
      // Storage is unavailable: the conversation lasts until the page is left
    }
  };

  const restore = () => {
    let stored = [];

    try {
      stored = JSON.parse(sessionStorage.getItem(STORE)) || [];
    } catch (error) {
      // Nothing to restore
    }

    const list = Array.isArray(stored) ? stored : [];
    const lastAgent = list.map((message) => message && message.role).lastIndexOf('agent');

    return list
      .filter((message) => message && (typeof message.text === 'string' || (message.role === 'agent' && Array.isArray(message.cards))))
      .map((message, index) => (message.role === 'agent' ? {
        role: 'agent',
        restored: true,
        cards: message.cards.filter((card) => card && typeof card.type === 'string'),
        agent: message.agent,
        // Only the last turn of a conversation that is still going on can be used
        closed: index !== lastAgent || !sessionStorage.getItem(AGENT),
      } : {
        role: message.role === 'user' ? 'user' : 'assistant',
        text: message.text,
        sources: cleanSources(message.sources),
        // What the answer can still be rated by, and how it was
        ref: typeof message.ref === 'string' ? message.ref : '',
        rating: [1, -1].includes(message.rating) ? message.rating : 0,
        explained: message.explained === true,
        offer: message.offer && Number(message.offer.id) > 0
          ? {
            id: Number(message.offer.id),
            title: String(message.offer.title || ''),
            text: String(message.offer.text || ''),
            button: String(message.offer.button || ''),
            source: message.offer.source === 'unhelpful' ? 'unhelpful' : 'offer',
            // A person's window opened from it: the offer became the handoff
            card: message.offer.card && message.offer.card.type === 'handoff' ? message.offer.card : null,
          }
          : null,
      }));
  };

  // ---------- Rating ----------

  // Sent and forgotten: a rating that does not arrive is not worth bothering the visitor about
  const sendRating = (message, feedback = '') => {
    const url = roots[0].dataset.feedback;

    if (!url || !message.ref || message.ref === 'demo') {
      return;
    }

    fetch(url, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json', ...embedHeaders() },
      credentials: 'same-origin',
      body: JSON.stringify({ ref: message.ref, rating: message.rating, feedback }),
    }).catch(() => {});
  };

  // ---------- Overlay ----------

  const dialog = el('dialog', 'mcp-ask-chat');

  dialog.tabIndex = -1;
  dialog.setAttribute('aria-label', strings.title);
  dialog.innerHTML = `
    <span class="mcp-ask-chat__grid" aria-hidden="true"></span>
    <span class="mcp-ask-chat__beam" aria-hidden="true" hidden></span>
    <div class="mcp-ask-visitor" aria-hidden="true" hidden>
      <img class="mcp-ask-visitor__ufo" alt="">
      <p class="mcp-ask-visitor__say"></p>
    </div>
    <div class="mcp-ask-chat__panel">
      <header class="mcp-ask-chat__head">
        <p class="mcp-ask-chat__title"></p>
        <button type="button" class="mcp-ask-chat__login" hidden></button>
        <button type="button" class="mcp-ask-chat__human" hidden></button>
        <button type="button" class="mcp-ask-chat__new"></button>
        <button type="button" class="mcp-ask-chat__close">${ICON_CLOSE}</button>
      </header>
      <div class="mcp-ask-chat__log" role="log"></div>
      <form class="mcp-ask-chat__composer">
        <textarea class="mcp-ask-chat__input" rows="1" maxlength="500" enterkeyhint="send"></textarea>
        <button type="submit" class="mcp-ask-chat__send">${ICON_SEND}</button>
      </form>
      <p class="mcp-ask-chat__note"></p>
    </div>`;

  const panel = dialog.querySelector('.mcp-ask-chat__panel');
  const log = dialog.querySelector('.mcp-ask-chat__log');
  const composer = dialog.querySelector('.mcp-ask-chat__composer');
  const field = dialog.querySelector('.mcp-ask-chat__input');
  const send = dialog.querySelector('.mcp-ask-chat__send');

  dialog.querySelector('.mcp-ask-chat__title').textContent = strings.title;
  dialog.querySelector('.mcp-ask-chat__new').textContent = strings.newChat;
