  // iOS lays its keyboard over the page without making the window any smaller, so whatever is
  // fixed to the bottom of the window ends up underneath it. The visual viewport says how much of
  // the window is covered; the open search box and the conversation keep to what is left.
  const viewport = window.visualViewport;

